import { Language } from '../types';

export interface LocalizedString {
  pt: string;
  en: string;
  es: string;
  de: string;
  fr: string;
  ru: string;
  nl: string;
  zh: string;
  he: string;
  sv: string;
  fi: string;
}

export function localize(
  lang: Language,
  texts?: Partial<Record<Language, string>> & { en?: string; pt?: string } | null
): string {
  if (!texts) return '';
  if (texts[lang]) return texts[lang]!;
  if (lang === 'pt' && texts.pt) return texts.pt;
  return texts.en || texts.pt || '';
}

